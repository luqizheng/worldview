using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace WorldView.Generator;

/// <summary>
/// 源生成器:读 assets/palettes/parchment_palette.yaml 的 ui.* 节点,
/// 为 WorldView.Ui.Theme.Palette (partial) 生成:
///   - Palette.Color.*    (Color 静态属性,#RRGGBB → Color.FromHtml("...ff"))
///   - Palette.Metric.*   (int 静态属性)
///   - Palette.Shadow.*   (int/float 静态属性)
///   - Palette.Modal.*    (float 静态属性)
///   - Palette.Animation.*(int 静态属性,毫秒)
/// 命名规则: yaml 段前缀(jrpg_/accent_)去掉后,其余下划线分段,首字母大写 → PascalCase。
/// 例: jrpg_fill_hover → JrpgFillHover
///     accent_vegetation_highlight → AccentVegetationHighlight
///     font_size_body → FontSizeBody
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class PaletteGenerator : IIncrementalGenerator
{
    private const string YamlRelativePath = "assets/palettes/parchment_palette.yaml";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 读 AdditionalFiles 中的 yaml。partial class 的存在由 source-init 阶段提供。
        var yamlTexts = context.AdditionalTextsProvider
            .Where(t => string.Equals(Path.GetFileName(t.Path), "parchment_palette.yaml", StringComparison.OrdinalIgnoreCase))
            .Select((t, ct) => t.GetText(ct)?.ToString() ?? "")
            .Collect();

        var partials = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (n, _) => n is ClassDeclarationSyntax cds && cds.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)),
                transform: static (ctx, ct) =>
                {
                    var symbol = ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct);
                    if (symbol is not INamedTypeSymbol ts) return null;
                    if (ts.ContainingNamespace?.ToDisplayString() != "WorldView.Ui.Theme") return null;
                    if (ts.Name != "Palette") return null;
                    return ts.ToDisplayString();
                })
            .Where(s => s is not null)
            .Collect();

        context.RegisterSourceOutput(yamlTexts.Combine(partials), (spc, pair) =>
        {
            var yaml = pair.Left.FirstOrDefault() ?? "";
            var hasPartial = pair.Right.Any(s => s is not null);

            // 1) yaml 错 → diagnostic 报告，**不**生成代码
            var entries = PaletteYamlParser.Parse(yaml, out var errors);
            foreach (var err in errors) ReportDiagnostic(spc, err);

            // 2) partial 缺失 → 报告要求添加 partial
            if (!hasPartial)
            {
                spc.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(
                        "WVP100",
                        "Palette partial 缺失",
                        "必须声明 partial class WorldView.Ui.Theme.Palette 才能让源生成器生成静态属性。",
                        "Palette",
                        DiagnosticSeverity.Warning,
                        isEnabledByDefault: true),
                    Location.None));
                return;
            }

            // 3) 生成 Palette.Designer.cs
            var src = RenderDesigner(entries);
            spc.AddSource("Palette.Designer.g.cs", SourceText.From(src, Encoding.UTF8));
        });
    }

    private static void ReportDiagnostic(SourceProductionContext ctx, string err)
    {
        // err 形如 "WVP003 ui.color.jrpg_bg ..." → 拆 code + message
        var space = err.IndexOf(' ');
        if (space < 0) { ctx.ReportDiagnostic(Diagnostic.Create(WvpUnknown, Location.None, err)); return; }
        var code = err.Substring(0, space);
        var msg = err.Substring(space + 1);
        var desc = code switch
        {
            PaletteYamlParser.WVP001 => Wvp001,
            PaletteYamlParser.WVP002 => Wvp002,
            PaletteYamlParser.WVP003 => Wvp003,
            PaletteYamlParser.WVP004 => Wvp004,
            PaletteYamlParser.WVP005 => Wvp005,
            PaletteYamlParser.WVP006 => Wvp006,
            _ => WvpUnknown,
        };
        ctx.ReportDiagnostic(Diagnostic.Create(desc, Location.None, msg));
    }

    private static string RenderDesigner(List<PaletteEntry> entries)
    {
        var sb = new StringBuilder(8192);
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// 由 WorldView.Generator.PaletteGenerator 编译期生成,不要手动修改。");
        sb.AppendLine("// 真源: assets/palettes/parchment_palette.yaml (ui.* 节)");
        sb.AppendLine("using Godot;");
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine("namespace WorldView.Ui.Theme;");
        sb.AppendLine();
        sb.AppendLine("public static partial class Palette");
        sb.AppendLine("{");

        // ---- Palette.Color.* ----
        var colors = entries.Where(e => e.Kind == EntryKind.Color).ToList();
        sb.AppendLine("    /// <summary>色值 token，#RRGGBB[AA] 来自 yaml ui.color.* 段。包含末尾 alpha 字节。</summary>");
        sb.AppendLine("    public static class Color");
        sb.AppendLine("    {");
        foreach (var e in colors)
        {
            var name = ToPascal(e.Key.Substring("ui.color.".Length));
            // Literal 已 lowerInvariant,且满足 #RRGGBB 或 #RRGGBBAA
            var html = e.Literal.Length == 7 ? e.Literal + "ff" : e.Literal;
            sb.AppendLine($"        /// <summary>{e.Key} = {e.Literal}</summary>");
            // 用 Godot.Color 全限定以避免和嵌套类 Color 同名冲突
            sb.AppendLine($"        public static readonly Godot.Color {name} = Godot.Color.FromHtml(\"{html}\");");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // ---- Palette.Metric.* / Shadow.* / Modal.* / Animation.* ----
        EmitNumericSection(sb, entries, "ui.metric", "Metric", "量化层(像素/字号/尺寸) 来自 yaml ui.metric.* 段。");
        EmitNumericSection(sb, entries, "ui.shadow", "Shadow", "阴影参数(偏移/大小/透明度) 来自 yaml ui.shadow.* 段。");
        EmitNumericSection(sb, entries, "ui.modal", "Modal", "模态遮罩参数 来自 yaml ui.modal.* 段。");
        EmitNumericSection(sb, entries, "ui.animation", "Animation", "动画时长(毫秒) 来自 yaml ui.animation.* 段。");

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitNumericSection(StringBuilder sb, List<PaletteEntry> all, string root, string className, string summary)
    {
        var items = all.Where(e => e.Key.StartsWith(root + ".")).ToList();
        if (items.Count == 0) return;
        sb.AppendLine($"    /// <summary>{summary}</summary>");
        sb.AppendLine($"    public static class {className}");
        sb.AppendLine("    {");
        foreach (var e in items)
        {
            var name = ToPascal(e.Key.Substring(root.Length + 1));
            // 用 const 不用 static readonly:让 Jrpg* 组件 const 字段可以引用编译期常量
            var lit = e.Literal;
            if (e.Kind == EntryKind.Int)
            {
                sb.AppendLine($"        /// <summary>{e.Key} = {lit}</summary>");
                sb.AppendLine($"        public const int {name} = {lit};");
            }
            else
            {
                // float 字面量加 'f' 后缀
                sb.AppendLine($"        /// <summary>{e.Key} = {lit}</summary>");
                sb.AppendLine($"        public const float {name} = {lit}f;");
            }
        }
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string ToPascal(string snake)
    {
        // "jrpg_fill_hover" → "JrpgFillHover"; "font_size_body" → "FontSizeBody"
        var parts = snake.Split('_', StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder(snake.Length);
        foreach (var p in parts)
        {
            if (p.Length == 0) continue;
            sb.Append(char.ToUpperInvariant(p[0]));
            if (p.Length > 1) sb.Append(p.AsSpan(1));
        }
        return sb.ToString();
    }

    // ---- Diagnostic descriptors ----
    private static readonly DiagnosticDescriptor Wvp001 = new(
        "WVP001", "yaml 读取失败", "读取 {0}", "Palette", DiagnosticSeverity.Error, isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor Wvp002 = new(
        "WVP002", "yaml 顶层结构错误", "顶层必须是 mapping: {0}", "Palette", DiagnosticSeverity.Error, isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor Wvp003 = new(
        "WVP003", "token 值类型错", "{0}", "Palette", DiagnosticSeverity.Error, isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor Wvp004 = new(
        "WVP004", "hex 格式错误", "{0}", "Palette", DiagnosticSeverity.Error, isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor Wvp005 = new(
        "WVP005", "路径不在允许段下", "{0}", "Palette", DiagnosticSeverity.Warning, isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor Wvp006 = new(
        "WVP006", "ui.color.* 命名不合法", "{0}", "Palette", DiagnosticSeverity.Warning, isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor WvpUnknown = new(
        "WVP000", "Palette 解析未知错", "{0}", "Palette", DiagnosticSeverity.Error, isEnabledByDefault: true);
}
